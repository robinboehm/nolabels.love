#!/usr/bin/env node
/**
 * Regenerates version.js and bumps the cache-busting `?v=` query params in
 * index.html from the current git state.
 *
 * App version format: "<commit count>-<short commit hash>" (e.g. "11-67f9002").
 * The commit count is a simple, ever-increasing number; the short hash lets
 * you pin down exactly which commit produced a given set of data. Because
 * this file has to be committed itself, the embedded hash necessarily
 * describes the *parent* commit rather than the one that ships it — that's
 * fine here, it's only meant for rough traceability/migration detection,
 * not exact reproducibility.
 *
 * Run manually with `node scripts/update-version.js`, or let the
 * `pre-commit` git hook (see .git/hooks/pre-commit) run it automatically
 * before every commit.
 */
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

function run(cmd) {
  return execSync(cmd, { encoding: 'utf8', cwd: path.join(__dirname, '..') }).trim();
}

const count = run('git rev-list --count HEAD');
const hash = run('git rev-parse --short HEAD');
const version = `${count}-${hash}`;

const versionFile = path.join(__dirname, '..', 'version.js');
const versionContent = `/**
 * Auto-generated by scripts/update-version.js — do not edit by hand.
 *
 * Format: "<commit count>-<short commit hash>" describing (roughly) the
 * commit this file was generated from. Loaded before data.js/app.js so
 * APP_VERSION is available globally. Stored alongside app data
 * (localStorage + exports) so a future version of the app can tell how
 * old a given set of data is and whether a migration might be needed.
 */
const APP_VERSION = '${version}';
`;
fs.writeFileSync(versionFile, versionContent);

const indexFile = path.join(__dirname, '..', 'index.html');
let html = fs.readFileSync(indexFile, 'utf8');
html = html.replace(/((?:version|data|app|style)\.(?:js|css))\?v=[^"']*/g, (_match, filename) => `${filename}?v=${count}`);
fs.writeFileSync(indexFile, html);

console.log(`version.js + index.html cache-busting params updated → ${version} (v=${count})`);
